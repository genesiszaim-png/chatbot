        "    elif operation == \"-\":\n",
        "        a = random.randint(10, 50)\n",
        "        b = random.randint(1, a)\n",
        "\n",
        "        question = f\"{a} - {b} = ?\"\n",
        "        answer = a - b\n",
        "\n",
        "    elif operation == \"×\":\n",
        "        a = random.randint(2, 12)\n",
        "        b = random.randint(2, 12)\n",
        "\n",
        "        question = f\"{a} × {b} = ?\"\n",
        "        answer = a * b\n",
        "\n",
        "    else:\n",
        "        # Create division questions with whole-number answers\n",
        "        b = random.randint(2, 12)\n",
