        "def create_options(correct_answer):\n",
        "    \"\"\"Create four multiple-choice options.\"\"\"\n",
        "\n",
        "    options = {correct_answer}\n",
        "\n",
        "    while len(options) < 4:\n",
        "        variation = random.randint(-10, 10)\n",
        "\n",
        "        if variation == 0:\n",
        "            continue\n",
        "\n",
        "        new_option = correct_answer + variation\n",
        "\n",
        "        if new_option >= 0:\n",
        "            options.add(new_option)\n",
        "\n",
        "    options = list(options)\n",
        "    random.shuffle(options)\n",
        "\n",
        "    return options\n",
