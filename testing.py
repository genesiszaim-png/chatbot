        "        try:\n",
        "            answer = int(input(f\"What is {num1} {operation} {num2}? \"))\n",
        "        except ValueError:\n",
        "            print(\"Invalid input. Please enter a number.\")\n",
        "            lives -= 1\n",
        "            print(\"You lost 1 life for invalid input.\")\n",
        "            continue # Skip to next question\n",
        "\n",
        "        # -----------------------------------------------------\n",
        "        # 5. CHECK THE ANSWER\n",
        "        # -----------------------------------------------------\n",
        "\n",
        "        if answer == correct_answer:\n",
        "            print(\"✅ Correct! +10 points!\")\n",
        "            score += 10\n",
        "\n",
        "        else:\n",
        "            print(\"❌ Incorrect!\")\n",
        "            print(\"The correct answer is:\", correct_answer)\n",
        "            lives -= 1\n",
        "            print(\"You lost 1 life.\")\n",
        "\n",
        "        # -----------------------------------------------------\n",
        "        # 6. DISPLAY GAME STATE\n",
        "        # -----------------------------------------------------\n",
        "\n",
        "        print(\"🏆 Score:\", score)\n",
        "        print(\"❤️ Lives:\", lives)\n",
        "\n",
        "        # -----------------------------------------------------\n",
        "        # 7. CHECK GAME OVER (DURING LEVEL)\n",
        "        # -----------------------------------------------------\n",
        "\n",
        "        if lives == 0:\n",
        "            print(\"\\n💥 GAME OVER!\")\n",
        "            break\n",
