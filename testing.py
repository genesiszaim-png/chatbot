        "            # Adjust num1 to be a multiple of num2, ensuring it's within range\n",
        "            # and that the quotient is a reasonable integer (e.g., between 1 and 10)\n",
        "            temp_quotient = random.randint(1, 10)\n",
        "            num1 = num2 * temp_quotient\n",
        "\n",
        "            # If num1 exceeds max_num, try to adjust it or re-roll numbers if necessary\n",
        "            attempts = 0\n",
        "            while (num1 > max_num or num1 < min_num) and attempts < 5:\n",
        "                num2 = random.randint(1, max_num)\n",
        "                if num2 == 0: # Ensure num2 is never zero\n",
        "                    num2 = 1\n",
        "                temp_quotient = random.randint(1, 10)\n",
        "                num1 = num2 * temp_quotient\n",
        "                attempts += 1\n",
