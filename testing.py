        "\n",
        "        elif operation == \"-\":\n",
        "            correct_answer = num1 - num2\n",
        "\n",
        "        elif operation == \"*\":\n",
        "            correct_answer = num1 * num2\n",
        "\n",
        "        elif operation == \"/\":\n",
        "            # Ensure integer division and avoid division by zero\n",
        "            # Make num1 a multiple of num2, and num2 not zero\n",
        "            # Adjust num2 to avoid division by zero\n",
        "            if num2 == 0:\n",
        "                num2 = random.randint(1, max_num) # Re-roll num2 if it's zero\n",
