        "        \"operations\": [\"+\", \"-\", \"*\"],\n",
        "        \"num_questions\": 5,\n",
        "    },\n",
        "    \"Advanced\": {\n",
        "        \"num_range\": (10, 20),\n",
        "        \"operations\": [\"+\", \"-\", \"*\", \"/\"],\n",
        "        \"num_questions\": 5,\n",
        "    },\n",
        "}\n",
