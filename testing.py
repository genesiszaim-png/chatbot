        "    \"Basic\": {\n",
        "        \"num_range\": (1, 10),\n",
        "        \"operations\": [\"+\", \"-\"],\n",
        "        \"num_questions\": 5,\n",
        "    },\n",
        "    \"Intermediate\": {\n",
