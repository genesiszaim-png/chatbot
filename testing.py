        "                    num1 = max_num - (max_num % num2 if num2 != 0 else 0) # Make it the largest multiple within range\n",
        "                if num1 < min_num:\n",
        "                    num1 = min_num + (num2 - (min_num % num2 if num2 != 0 else 0)) % num2\n",
        "                if num1 == 0 and min_num > 0:\n",
        "                    num1 = num2\n",
        "\n",
        "            correct_answer = num1 // num2 # Use integer division\n",
        "\n",
        "\n",
        "        # -----------------------------------------------------\n",
        "        # 4. ASK THE PLAYER\n",
        "        # -----------------------------------------------------\n",
        "\n",
        "        print(f\"\\n{level_name} Question {question_num}:\")\n",
